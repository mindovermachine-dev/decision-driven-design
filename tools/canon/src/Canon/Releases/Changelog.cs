using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Canon.Configuration;
using Canon.Infrastructure;

namespace Canon.Releases;

/// <summary>
/// CHANGELOG.md as the projection of releases/ (DDD-dec-104; Varve's
/// eng/changelog.cs). Above the frozen tail, the file is rendered from the
/// descriptors and nothing else, newest first by version precedence. The tail
/// (the 4.x headings) is kept byte for byte and checked against a SHA-256 in
/// canon.yaml.
///
/// No section says whether its version is cut. A projection that read tag
/// state would change when a tag is pushed, with no commit to show for it,
/// and CHANGELOG.md would go stale on every release. Whether a version is cut
/// is a question for its tag (TagPresence), not for this file. DDD-dec-104's
/// resolution lists "whether it is cut"; this departs from that line and says
/// so (successor item S-10).
/// </summary>
internal static class Changelog
{
    public static IReadOnlyList<Descriptor> LoadDescriptors(string root, CanonConfig config)
    {
        string directory = Path.Combine(root, config.Releases);
        if (!Directory.Exists(directory))
        {
            return [];
        }

        return Directory.GetFiles(directory, "v*.yaml")
            .Select(path => Descriptor.Parse(config.Releases.TrimEnd('/') + "/" + Path.GetFileName(path), File.ReadAllText(path)))
            .ToList();
    }

    public static string Render(IReadOnlyList<Descriptor> descriptors, string tail, CanonConfig config)
    {
        StringBuilder text = new();
        text.Append("# Changelog\n\n");
        text.Append("<!-- Generated by `canon changelog` from ").Append(config.Releases).Append("/*.yaml (DDD-dec-104).\n");
        text.Append("     Edit the release descriptors, not this file. The headings from \"")
            .Append(config.ChangelogTailFrom).Append("\" on are a\n");
        text.Append("     frozen tail, kept byte for byte (canon.yaml, changelog.tail-sha256). -->\n\n");

        foreach (Descriptor descriptor in descriptors.OrderByDescending(d => Precedence(d.Version)))
        {
            string version = descriptor.Version ?? "(no version)";
            text.Append("## ").Append(version).Append(" — ").Append(descriptor.Title?.Trim()).Append("\n\n");
            text.Append(descriptor.Date ?? "(no date)");
            if (descriptor.Prerelease)
            {
                text.Append(" · pre-release");
            }

            text.Append(" · descriptor [`").Append(descriptor.Path).Append("`](").Append(descriptor.Path).Append(")\n\n");
            text.Append((descriptor.Summary ?? "").Trim()).Append("\n\n");
        }

        return text.Append(tail).ToString();
    }

    /// <summary>The frozen tail of a changelog's text: from its first line equal to the marker heading, to the end.</summary>
    public static string? Tail(string text, string marker)
    {
        if (text.StartsWith(marker + "\n", StringComparison.Ordinal))
        {
            return text;
        }

        int at = text.IndexOf("\n" + marker + "\n", StringComparison.Ordinal);
        return at < 0 ? null : text[(at + 1)..];
    }

    public static string Sha256(string text) =>
        Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(text)));

    /// <summary>
    /// The projection for a working tree, or the reasons there is none: no
    /// tail marker configured, the tail missing, or the tail not what
    /// canon.yaml recorded.
    /// </summary>
    public static (string? Projection, IReadOnlyList<string> Problems) Project(string root, CanonConfig config)
    {
        if (config.ChangelogTailFrom is null || config.ChangelogTailSha256 is null)
        {
            return (null, [$"{CanonConfig.FileName} declares no changelog.tail-from and changelog.tail-sha256"]);
        }

        string path = Path.Combine(root, config.ChangelogPath);
        if (!File.Exists(path))
        {
            return (null, [$"{config.ChangelogPath} does not exist, so its frozen tail cannot be read"]);
        }

        string? tail = Tail(File.ReadAllText(path), config.ChangelogTailFrom);
        if (tail is null)
        {
            return (null, [$"{config.ChangelogPath} has no line \"{config.ChangelogTailFrom}\": the frozen tail is gone"]);
        }

        string hash = Sha256(tail);
        if (!string.Equals(hash, config.ChangelogTailSha256, StringComparison.Ordinal))
        {
            return (null, [$"the frozen tail of {config.ChangelogPath} was edited: sha256 {hash}, recorded {config.ChangelogTailSha256}"]);
        }

        IReadOnlyList<Descriptor> descriptors = LoadDescriptors(root, config);
        List<string> problems = descriptors
            .Where(d => d.Version is null || d.Title is null || d.Summary is null)
            .Select(d => $"{d.Path}: version, title and summary are needed to render it")
            .ToList();
        return problems.Count > 0 ? (null, problems) : (Render(descriptors, tail, config), []);
    }

    private static (int, int, int) Precedence(string? version)
    {
        if (version is null || !Descriptor.VersionPattern().IsMatch(version))
        {
            return (-1, -1, -1);
        }

        int[] parts = version[1..].Split('.').Select(p => int.Parse(p, CultureInfo.InvariantCulture)).ToArray();
        return (parts[0], parts[1], parts[2]);
    }
}
